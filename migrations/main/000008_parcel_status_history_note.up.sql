-- Нэгж талбарын төлөв солих ШАЛТГААН.
--
-- ШИНЭ ХҮСНЭГТ ҮҮСГЭХГҮЙ — байгаа parcel_status_history дээр нэг багана
-- нэмнэ. Ингэснээр төлөв бүрийн шалтгаан нь тухайн шилжилтийн мөр дээрээ
-- хадгалагдана (тусдаа хүснэгт, JOIN шаардлагагүй).
--
-- "Нөлөөлөгдсөн гарсан" (3) ба "Татгалзсан" (4) төлөвт шилжихэд ЗААВАЛ
-- бөглөнө (backend 400 буцаана); бусад төлөвт ХООСОН байж болно. Хуучин
-- бүх мөр NULL байна.
ALTER TABLE public.parcel_status_history
    ADD COLUMN IF NOT EXISTS reason text;

COMMENT ON COLUMN public.parcel_status_history.reason IS
    'Төлөв солих шалтгаан. Нөлөөлөгдсөн гарсан / Татгалзсан үед заавал, бусад үед хоосон байж болно.';
