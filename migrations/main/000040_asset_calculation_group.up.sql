-- Өртгийн хандлагын мөр бүр ЭКСЭЛ дээрх бүлгээ (merge хийсэн "Итгэлцүүр" г.м)
-- өөртөө авч явна.
--
-- ЯАГААД: бүлэг өмнө нь ЗӨВХӨН `asset_calc_type.grp` (лавлах) дээр байсан.
-- Импортод мөрийн нэр нь одоо байгаа төрөлтэй таарвал тэр төрлийн id-гаар
-- хадгалагддаг ба Excel-ийн бүлэг АЛДАГДДАГ. Лавлахад суулгасан төрлүүдийн
-- ихэнх нь grp=''-тэй тул нэг бүлгийн мөрүүд тасалдаж, дэлгэц дээр "Итгэлцүүр"
-- гурван тусдаа нүд болж хуваагдаж байв (rowspan зөвхөн ЗЭРЭГЦЭЭ мөрийг нэгтгэнэ).
--
-- Мөр тус бүрийн бүлгийг энд хадгалснаар хүснэгт нь Excel-тэй ЯГ адил
-- харагдана. Хоосон үед лавлахын grp руу ухарна (хуучин өгөгдөл).
ALTER TABLE public.asset_calculation
    ADD COLUMN IF NOT EXISTS grp text DEFAULT ''::text NOT NULL;

COMMENT ON COLUMN public.asset_calculation.grp IS
    'Excel дэх мөрийн бүлэг (Итгэлцүүр г.м). Хоосон бол asset_calc_type.grp хэрэглэнэ.';
