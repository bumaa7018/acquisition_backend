-- ЗАХИРАМЖИЙН ТӨСЛИЙН ДУГААР — ТУХАЙН ОНДОО ДАВХАРДАХГҮЙ.
--
-- Нэг захирамжийн дугаар (жишээ нь А/280) нь ӨӨР ОНУУДАД дахин ашиглагддаг
-- тул дан дугаараар unique болгож БОЛОХГҮЙ. Харин НЭГ ОНЫ дотор давхардвал
-- аль нь зөв болох нь тодорхойгүй болж, импорт ба дэлгэц хоёулаа алддаг.
--
-- ДУГААРЫГ ХЭВИЙН БОЛГОЖ тулгана — эх сурвалж дээр нэг дугаар олон янзаар
-- бичигддэг:
--
--     А/280  ·  A/280 (латин "A")  ·  А-280  ·  А 280
--
-- тул кирилл болгож, зураас/налуу/зайг хасна. Ингэснээр дээрх дөрвүүлэн
-- ижил түлхүүр болно.
--
-- ХЭСЭГЧИЛСЭН (partial) индекс: огноогүй эсвэл дугааргүй ноорог нь оноороо
-- ялгагдах боломжгүй тул хязгаарлалтаас гадуур үлдэнэ.
CREATE UNIQUE INDEX IF NOT EXISTS uq_decision_draft_decree_per_year
    ON public.decision_draft (
        regexp_replace(replace(upper(decree_number), 'A', 'А'), '[-/[:space:]]', '', 'g'),
        EXTRACT(YEAR FROM decision_date)
    )
    WHERE NULLIF(decree_number, '') IS NOT NULL
      AND decision_date IS NOT NULL;
