-- Нэгж талбарын СҮҮЛИЙН статусын огноог хурдан олох индекс.
--
-- ЯАГААД: дашбоард болон тайлангийн ЖИЛИЙН шүүлт нь нэгж талбар бүрийн
-- хамгийн сүүлийн статусын огноог correlated дэд асуулгаар олдог:
--
--   EXTRACT(YEAR FROM (SELECT MAX(psh.status_date)
--                        FROM parcel_status_history psh
--                       WHERE psh.parcel_id = p.parcel_id)) IN (...)
--
-- Энэ нь нэгж талбар тутамд НЭГ удаа ажиллах ба дашбоардын 8 дэд асуулга
-- тус бүрд давтагдана. Өмнө нь зөвхөн `idx_psh_parcel (parcel_id)` байсан
-- тул MAX() нь тухайн талбарын БҮХ мөрийг heap-ээс уншиж байлаа.
--
-- ХЭМЖИЛТ (100 чөлөөлөлт / 10,000 талбар / 50,000 түүх, тусгаарласан perfdb):
--
--                      өмнө          дараа
--   subquery cost      230,681       13,055      (17.7 дахин бага)
--   буфер              70,368        30,369
--   heap fetches       50,000        0           (index-only scan)
--   dashboard+жил      30с+ timeout  327 мс      (1 хэрэглэгч)
--                      —             2.43 с      (10 зэрэгцээ, p95)
--
-- `status_date DESC` нь MAX()-ыг индексийн эхний мөрөөс шууд авах боломж
-- өгнө; хоёр баганат индекс нь `parcel_id`-гаар хайх хуучин хэрэглээг мөн
-- бүрэн орлоно (тиймээс дор нь илүүдэл болсон индексийг хасав).
--
-- PRODUCTION-Д АНХААРАХ: энэ нь энгийн CREATE INDEX тул бүтээх хугацаанд
-- parcel_status_history-д БИЧИХ үйлдэл хүлээнэ (унших саадгүй). Хүснэгт маш
-- том бол migration-ыг ажлын бус цагт ажиллуулах, эсвэл CREATE INDEX
-- CONCURRENTLY-г гар аргаар (гүйлгээнээс гадуур) урьдчилан гүйцэтгэнэ.
CREATE INDEX IF NOT EXISTS idx_psh_parcel_status_date
    ON public.parcel_status_history USING btree (parcel_id, status_date DESC);

-- ИЛҮҮДЭЛ болсон индекс: (parcel_id) нь дээрх индексийн эхний багана тул
-- түүгээр хайх бүх асуулгыг шинэ индекс үйлчилнэ. Үлдээвэл INSERT бүрд
-- хоёр индекс шинэчлэгдэж, диск дэмий эзэлнэ.
DROP INDEX IF EXISTS public.idx_psh_parcel;
