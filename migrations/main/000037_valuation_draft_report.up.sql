-- БАТАЛГААЖААГҮЙ (төслийн) үнэлгээний тайлангийн хавсралт.
--
-- ЯАГААД: үнэлгээг санхүүд ИЛГЭЭХЭД мэргэжлийн байгууллага өөрийн бэлтгэсэн
-- тайланг (PDF эсвэл Word) хамт өгөх ёстой — санхүүгийн мэргэжилтэн зөвхөн
-- тоо харж биш, үндэслэлийг нь уншиж баталгаажуулдаг. Одоо байгаа
-- `valuation_report` баримт нь БАТАЛГААЖСАНЫ ДАРАА хавсаргагддаг өөр зүйл тул
-- түүнтэй хольж болохгүй.
--
-- ЯАГААД submission дээр: тайлан нь тухайн нэгж талбар + урсгалын ИЛГЭЭЛТЭД
-- харьяалагдана. Илгээх бүрд шинээр хавсаргаж (солигдож) болох ба буцаагдаад
-- дахин илгээхэд шинэ хувилбар нь хуучныг орлоно. Ингэснээр "хамгийн сүүлд
-- илгээсэн юу вэ" гэдэг нэг мөрөөс тодорхой байна.
--
-- ЯЛГАА: attachment_url/attachment_name нь СҮҮЛИЙН үйлдлийн (буцаах/цуцлах)
-- хавсралт бөгөөд үйлдэл бүрд дарж бичигддэг. Тайлан тэнд байвал буцаалтын
-- дараа алга болно — тиймээс ТУСДАА багана.
ALTER TABLE public.parcel_valuation_submission
    ADD COLUMN IF NOT EXISTS draft_report_url text DEFAULT ''::text NOT NULL,
    ADD COLUMN IF NOT EXISTS draft_report_name text DEFAULT ''::text NOT NULL;

COMMENT ON COLUMN public.parcel_valuation_submission.draft_report_url IS
    'Баталгаажаагүй үнэлгээний тайлан (PDF/Word). Зөвхөн ИЛГЭЭХ үйлдлээр тавигдана.';
COMMENT ON COLUMN public.parcel_valuation_submission.draft_report_name IS
    'Тайлангийн эх файлын нэр (хэрэглэгчид харуулна).';
